"""Build the public static website from the database.

The site is plain HTML/CSS with a little JavaScript for the catalog search. It is
generated by GitHub Actions and published to GitHub Pages, so there is no server
and no secret is ever exposed to visitors.

Feed data is untrusted input: every value from the database goes through
html.escape before it is placed in a page, so a malicious string in a feed
cannot inject script into the site.
"""

import logging
import shutil
import sqlite3
from datetime import UTC, date, datetime, timedelta
from html import escape
from importlib import resources
from pathlib import Path
from string import Template
from urllib.parse import quote

from intelbrief.config import CONTACT_URL

logger = logging.getLogger(__name__)

RECENT_DAYS = 30
NAV_PAGES = [("index.html", "Overview"), ("catalog.html", "Full catalog"), ("about.html", "About")]
STATIC_FILES = ["style.css", "filter.js"]

NVD_URL = "https://nvd.nist.gov/vuln/detail/"
CISA_SEARCH_URL = (
    "https://www.cisa.gov/known-exploited-vulnerabilities-catalog?search_api_fulltext="
)


def _asset(name: str) -> str:
    """Read a file from the site_assets folder that ships inside the package."""
    return resources.files("intelbrief").joinpath("site_assets", name).read_text(encoding="utf-8")


def load_kev(conn: sqlite3.Connection) -> list[sqlite3.Row]:
    """Return every KEV entry, newest additions first."""
    return conn.execute(
        """
        SELECT cve_id, vendor_project, product, vulnerability_name, date_added,
               short_description, required_action, due_date, known_ransomware_use
        FROM kev_entries
        ORDER BY date_added DESC, cve_id DESC
        """
    ).fetchall()


def _text(value: str | None, fallback: str = "Not listed") -> str:
    """Escape a database value for HTML, showing a fallback when it is missing."""
    return escape(value) if value else f'<span class="muted">{fallback}</span>'


def _kev_row(row: sqlite3.Row) -> str:
    """One table row for a KEV entry."""
    cve = row["cve_id"]
    ransomware = row["known_ransomware_use"]
    search_text = " ".join(
        filter(None, [cve, row["vendor_project"], row["product"], row["vulnerability_name"]])
    ).lower()
    badge = (
        '<span class="badge badge-alert">Known</span>'
        if ransomware
        else '<span class="muted">Not known</span>'
    )
    return f"""
<tr data-search="{escape(search_text)}" data-ransomware="{int(ransomware)}">
  <td class="cve">
    <a href="{NVD_URL}{quote(cve)}" rel="noopener">{escape(cve)}</a>
    <a class="src" href="{CISA_SEARCH_URL}{quote(cve)}" rel="noopener">CISA</a>
  </td>
  <td><strong>{_text(row["vendor_project"])}</strong><br>{_text(row["product"])}</td>
  <td>
    <span class="vuln-name">{_text(row["vulnerability_name"])}</span>
    <p class="desc">{_text(row["short_description"], "No description provided.")}</p>
  </td>
  <td class="date" data-label="Added">{_text(row["date_added"])}</td>
  <td class="date" data-label="Federal due date">{_text(row["due_date"])}</td>
  <td data-label="Ransomware use">{badge}</td>
</tr>"""


def _kev_table(rows: list[sqlite3.Row], table_id: str) -> str:
    """A full KEV table, wrapped so it scrolls sideways on small screens."""
    body = "".join(_kev_row(r) for r in rows)
    return f"""
<div class="table-wrap">
<table id="{table_id}">
  <thead>
    <tr>
      <th scope="col">CVE</th>
      <th scope="col">Vendor / product</th>
      <th scope="col">Vulnerability</th>
      <th scope="col">Added</th>
      <th scope="col">Federal due date</th>
      <th scope="col">Ransomware use</th>
    </tr>
  </thead>
  <tbody>{body}</tbody>
</table>
</div>"""


def _stat(value: int, label: str) -> str:
    return f'<div class="stat"><span class="stat-value">{value:,}</span>{label}</div>'


def _page(filename: str, title: str, content: str, generated_at: datetime) -> str:
    """Wrap page content in the shared layout (header, navigation, footer)."""
    current = ' aria-current="page"'
    nav = "".join(
        f'<a href="{href}"{current if href == filename else ""}>{label}</a>'
        for href, label in NAV_PAGES
    )
    return Template(_asset("base.html")).substitute(
        title=escape(title),
        nav=nav,
        content=content,
        updated=generated_at.strftime("%Y-%m-%d %H:%M UTC"),
        repo_url=CONTACT_URL,
    )


def _overview(rows: list[sqlite3.Row], today: date) -> str:
    week_ago = (today - timedelta(days=7)).isoformat()
    cutoff = (today - timedelta(days=RECENT_DAYS)).isoformat()
    recent = [r for r in rows if (r["date_added"] or "") >= cutoff]
    last_week = sum(1 for r in recent if r["date_added"] >= week_ago)
    ransomware = sum(1 for r in rows if r["known_ransomware_use"])

    if recent:
        table = _kev_table(recent, "recent")
    else:
        table = (
            f'<p class="empty">No vulnerabilities were added in the last {RECENT_DAYS} days.</p>'
        )

    return f"""
<section class="hero">
  <h1>Known exploited vulnerabilities, made readable</h1>
  <p class="lede">A daily view of the
    <a href="https://www.cisa.gov/known-exploited-vulnerabilities-catalog">CISA Known
    Exploited Vulnerabilities (KEV) catalog</a>: flaws attackers are confirmed to be using
    right now. If your organization runs one of these products, patching it should come
    before almost anything else.</p>
</section>
<section class="stats" aria-label="Catalog statistics">
  {_stat(len(rows), "in the catalog")}
  {_stat(last_week, "added in the last 7 days")}
  {_stat(len(recent), f"added in the last {RECENT_DAYS} days")}
  {_stat(ransomware, "linked to ransomware")}
</section>
<section>
  <h2>Added in the last {RECENT_DAYS} days</h2>
  <p class="hint">CVE IDs link to the NVD entry; “CISA” links to the official KEV record.</p>
  {table}
  <p><a href="catalog.html">Search the full catalog →</a></p>
</section>"""


def _catalog(rows: list[sqlite3.Row]) -> str:
    return f"""
<h1>Full KEV catalog</h1>
<form class="filters" role="search" onsubmit="return false">
  <label for="q">Search CVE, vendor, product or vulnerability name</label>
  <input id="q" type="search" placeholder="e.g. Fortinet, Exchange, CVE-2024-" autocomplete="off">
  <label class="check"><input id="ransomware-only" type="checkbox"> Ransomware use known</label>
  <p id="count" class="hint" aria-live="polite">{len(rows):,} vulnerabilities</p>
</form>
{_kev_table(rows, "catalog")}
<script src="filter.js"></script>"""


def build_site(
    conn: sqlite3.Connection,
    out_dir: Path,
    today: date | None = None,
    generated_at: datetime | None = None,
) -> list[Path]:
    """Write the static site into out_dir, replacing what was there. Returns the files written."""
    generated_at = generated_at or datetime.now(UTC)
    today = today or generated_at.date()
    rows = load_kev(conn)

    pages = {
        "index.html": ("IntelBrief: Known exploited vulnerabilities", _overview(rows, today)),
        "catalog.html": ("Full KEV catalog · IntelBrief", _catalog(rows)),
        "about.html": ("About · IntelBrief", _asset("about.html")),
    }

    # Start from an empty folder so pages removed from the code don't linger online.
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    written = []
    for filename, (title, content) in pages.items():
        path = out_dir / filename
        path.write_text(_page(filename, title, content, generated_at), encoding="utf-8")
        written.append(path)
    for name in STATIC_FILES:
        path = out_dir / name
        path.write_text(_asset(name), encoding="utf-8")
        written.append(path)

    logger.info("Built site with %d KEV entries into %s", len(rows), out_dir)
    return written
